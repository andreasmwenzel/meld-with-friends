/**
 * The words of bot table talk: one voice per bot, each rooted in its name, plus a neutral voice
 * for any other name. Lines may only use `{bidder}` and `{partner}`, and only where the picker
 * fills them meaningfully (see the comments per situation). They refer to public results only.
 */
export const SITUATIONS = [
  "selfMade", // the speaker bid and made it. No {bidder} (it is the speaker).
  "partnerMade", // the speaker's partner bid and made it. {bidder} is the partner.
  "ownSet", // the speaker's side went set; either of them may have bid. No {bidder}. Be kind.
  "opponentMade", // an opponent made a big bid. {bidder} is that opponent.
  "opponentSmallMade", // an opponent made an ordinary bid. {bidder} is that opponent.
  "opponentSet", // the speaker's side set the opponents. {bidder} is the opponent who bid.
  "shootMade", // a moon shoot took every trick. Either side may have shot. No names.
  "shootMissed", // a moon shoot failed. Either side may have shot. No names, no gloating.
  "bigMeld", // either side laid down a lot of meld. No names.
  "leading", // the speaker's side leads by a lot.
  "trailing", // the speaker's side trails by a lot.
  "win", // the speaker's side won the game.
  "loss", // the other side won the game.
  "redeal", // throw-in or all-pass redeal. No {bidder}.
  "rematch", // a rematch started. No {bidder}.
] as const;
export type TalkSituation = typeof SITUATIONS[number];
export type Voice = Readonly<Record<TalkSituation, readonly string[]>>;

